-- Memo Lake schema.
-- Written in SQL that runs unchanged on PostgreSQL and on H2 (MODE=PostgreSQL).
-- All timestamps are stored as TIMESTAMP WITH TIME ZONE and written in UTC by the application.

CREATE TABLE topic (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)                NOT NULL,
    description VARCHAR(1000)               NOT NULL DEFAULT '',
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_topic_name UNIQUE (name)
);

CREATE TABLE memo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id   BIGINT                      NOT NULL,
    name       VARCHAR(100)                NOT NULL,
    -- Raw memo body. Never parsed or transformed by the server.
    content    TEXT                        NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version    BIGINT                      NOT NULL,
    CONSTRAINT fk_memo_topic FOREIGN KEY (topic_id) REFERENCES topic (id),
    -- Also serves lookups by (topic, memo name).
    CONSTRAINT uk_memo_topic_name UNIQUE (topic_id, name)
);

-- Serves both "memos of a topic, newest first" (ORDER BY updated_at DESC, name)
-- and "latest memo modification per topic" (MAX(updated_at) WHERE topic_id = ?).
CREATE INDEX idx_memo_topic_updated ON memo (topic_id, updated_at DESC, name);
